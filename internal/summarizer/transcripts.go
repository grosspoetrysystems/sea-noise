// Package summarizer ports references/scripts/summarize-transcripts.py
// in a skill-executed shape: instead of inline prompts, it invokes
// declarative skills from .agents/shared/skills/inference/ via the
// skill executor. The transcript-path is implemented; web-clip path
// and tag enrichment are deferred to a follow-up.
package summarizer

import (
	"context"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"sea-noise/internal/ai/skill"
	"sea-noise/internal/markdown"
)

const (
	// MinContentChars matches references/scripts/summarize-transcripts.py:MIN_CONTENT_CHARS.
	// Skips memes, short clips, oddities.
	MinContentChars = 500

	// MaxContentChars matches the prototype's MAX_CONTENT_CHARS truncation
	// before sending to the model.
	MaxContentChars = 80000
)

// EnrichTranscriptsInput configures a transcript-enrichment run.
type EnrichTranscriptsInput struct {
	VaultRoot  string   // absolute path to the vault root
	SearchDirs []string // vault-relative dirs to scan (default mirrors prototype)
}

// EnrichTranscriptsResult reports counts and per-note outcomes.
type EnrichTranscriptsResult struct {
	Updated []string // relative paths that were enriched
	Skipped []string // relative paths that didn't qualify
	Failed  []string // relative paths where enrichment failed (kept original)
}

// DefaultSearchDirs is the prototype's default search set.
var DefaultSearchDirs = []string{
	"notes/fleeting",
	"notes/references",
	"inbox",
}

// summarizeContentInput is the data the summarize-content skill template
// expects. Field names match the template's {{.Field}} references.
type summarizeContentInput struct {
	Content           string
	TitleContext      string
	SourceDescription string
}

// EnrichTranscripts walks the configured vault directories, finds
// markdown notes containing a `## Transcript` section that isn't
// already enriched, and prepends a `## Research Context` section
// generated by the summarize-content skill.
//
// Returns an EnrichTranscriptsResult listing what happened to each
// note. The first error encountered during file IO is returned
// alongside; per-note inference failures are recorded in Failed
// without aborting the run.
func EnrichTranscripts(ctx context.Context, exec *skill.Executor, in EnrichTranscriptsInput) (EnrichTranscriptsResult, error) {
	var result EnrichTranscriptsResult

	dirs := in.SearchDirs
	if len(dirs) == 0 {
		dirs = DefaultSearchDirs
	}

	for _, rel := range dirs {
		dir := filepath.Join(in.VaultRoot, rel)
		entries, err := os.ReadDir(dir)
		if errors.Is(err, os.ErrNotExist) {
			continue
		}
		if err != nil {
			return result, fmt.Errorf("read %s: %w", dir, err)
		}

		paths := make([]string, 0, len(entries))
		for _, e := range entries {
			if e.IsDir() || !strings.HasSuffix(e.Name(), ".md") {
				continue
			}
			paths = append(paths, filepath.Join(dir, e.Name()))
		}
		sort.Strings(paths)

		for _, p := range paths {
			outcome, err := enrichOne(ctx, exec, in.VaultRoot, p)
			if err != nil {
				return result, err
			}
			switch outcome.kind {
			case outcomeUpdated:
				result.Updated = append(result.Updated, outcome.rel)
			case outcomeSkipped:
				result.Skipped = append(result.Skipped, outcome.rel)
			case outcomeFailed:
				result.Failed = append(result.Failed, outcome.rel)
			}
		}
	}

	return result, nil
}

type outcomeKind int

const (
	outcomeSkipped outcomeKind = iota
	outcomeUpdated
	outcomeFailed
)

type outcome struct {
	kind outcomeKind
	rel  string
}

// enrichOne processes a single note. Returns:
//   - (outcomeSkipped, nil) if the note doesn't qualify (no transcript,
//     already enriched, transcript too short)
//   - (outcomeUpdated, nil) on successful enrichment
//   - (outcomeFailed, nil) if the inference call failed (note left
//     untouched)
//   - (_, err) if a real IO error happened (caller aborts the run)
func enrichOne(ctx context.Context, exec *skill.Executor, vaultRoot, path string) (outcome, error) {
	rel, _ := filepath.Rel(vaultRoot, path)

	raw, err := os.ReadFile(path)
	if err != nil {
		return outcome{}, fmt.Errorf("read %s: %w", path, err)
	}
	content := string(raw)

	fm, err := markdown.ParseFrontmatterYAML(content)
	if err != nil {
		return outcome{kind: outcomeSkipped, rel: rel}, nil
	}
	body := fm.Body

	transcriptHeader := "## Transcript"
	idx := strings.Index(body, transcriptHeader)
	if idx < 0 {
		return outcome{kind: outcomeSkipped, rel: rel}, nil
	}
	if isAlreadyEnriched(body) {
		return outcome{kind: outcomeSkipped, rel: rel}, nil
	}

	transcript := strings.TrimSpace(body[idx+len(transcriptHeader):])
	if len(transcript) < MinContentChars {
		return outcome{kind: outcomeSkipped, rel: rel}, nil
	}

	title, _ := fm.Fields["title"].(string)
	if title == "" {
		title = strings.TrimSuffix(filepath.Base(path), ".md")
	}

	trimmed := transcript
	if len(trimmed) > MaxContentChars {
		trimmed = trimmed[:MaxContentChars]
	}

	titleContext := ""
	if title != "" {
		titleContext = fmt.Sprintf(" about '%s'", title)
	}

	response, err := exec.Execute(ctx, "summarize-content", summarizeContentInput{
		Content:           trimmed,
		TitleContext:      titleContext,
		SourceDescription: "a YouTube video transcript",
	})
	if err != nil {
		return outcome{kind: outcomeFailed, rel: rel}, nil
	}

	// Splice "## Research Context" section BEFORE the transcript header.
	// This mirrors the prototype's process_transcript_note:
	//   before = content[:idx].rstrip()
	//   after  = content[idx:]
	//   post.content = f"{before}\n\n## Research Context\n\n{summary}\n\n{after}\n"
	before := strings.TrimRight(body[:idx], " \t\n")
	after := body[idx:]
	newBody := fmt.Sprintf("%s\n\n## Research Context\n\n%s\n\n%s\n", before, response, after)

	newRaw := reassembleNote(raw, fm.Body, newBody)
	if err := os.WriteFile(path, []byte(newRaw), 0o644); err != nil {
		return outcome{}, fmt.Errorf("write %s: %w", path, err)
	}
	return outcome{kind: outcomeUpdated, rel: rel}, nil
}

// isAlreadyEnriched matches the prototype's check.
func isAlreadyEnriched(content string) bool {
	return strings.Contains(content, "## Research Context") || strings.Contains(content, "## Key Takeaways")
}

// reassembleNote replaces the body portion of a note while preserving
// the leading frontmatter block verbatim. raw is the original file
// contents; oldBody is what ParseFrontmatterYAML returned as Body
// (post-frontmatter, lstripped); newBody is the replacement.
//
// We splice by finding the body suffix in raw and substituting it.
// Frontmatter delimiters and any leading whitespace before the body
// are preserved exactly.
func reassembleNote(raw []byte, oldBody, newBody string) string {
	rawStr := string(raw)
	// Locate the start of the body in raw. ParseFrontmatterYAML left-
	// trims, so oldBody may not match raw byte-for-byte at the
	// boundary. Find by suffix of oldBody.
	if oldBody == "" {
		// No frontmatter or empty body — just return newBody.
		return newBody
	}
	idx := strings.Index(rawStr, oldBody)
	if idx < 0 {
		// Fallback: replace the entire content. Frontmatter would be
		// lost. This branch shouldn't fire on well-formed notes.
		return newBody
	}
	return rawStr[:idx] + newBody
}
